-- Stride database schema.
-- Run the whole file in the Supabase SQL editor. It is safe to run again.
--
-- Every table belongs to one user through user_id, and RLS lets a signed-in
-- user see and change only their own rows. Child rows (logs, exercises,
-- exercise logs, daily selections) use composite foreign keys on
-- (parent id, user_id), so a row can only point at a parent owned by the same user.
--
-- Default trackers and muscle groups are created per user by the app at sign-up
-- (src/app/(auth)/signup/page.js) and on the first visit to /fitness, so there is
-- no shared seed data. A trigger creates an empty profile row for every new user.

-- Profiles ------------------------------------------------------------------

create table if not exists public.profiles (
  user_id uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  name text,
  gender text,
  avatar_seed text,
  age integer,
  height_cm numeric,
  weight_kg numeric,
  has_seen_tour boolean not null default false,
  created_at timestamptz not null default now()
);

-- Trackers and logs ---------------------------------------------------------

create table if not exists public.trackers (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  unit text not null default 'units',
  target_value numeric not null,
  type text not null default 'number',
  created_at timestamptz not null default now(),
  unique (id, user_id)
);

create table if not exists public.logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  tracker_id bigint not null,
  value numeric not null,
  logged_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  foreign key (tracker_id, user_id) references public.trackers (id, user_id) on delete cascade
);

-- Notes ---------------------------------------------------------------------

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  title text not null default 'Untitled',
  content text not null default '',
  created_at timestamptz not null default now()
);

-- Fitness -------------------------------------------------------------------

create table if not exists public.muscle_groups (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now(),
  unique (id, user_id)
);

create table if not exists public.exercises (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  muscle_group_id bigint not null,
  name text not null,
  created_at timestamptz not null default now(),
  unique (id, user_id),
  foreign key (muscle_group_id, user_id) references public.muscle_groups (id, user_id) on delete cascade
);

create table if not exists public.exercise_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  exercise_id bigint not null,
  sets integer not null,
  reps integer not null,
  weight numeric,
  logged_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  foreign key (exercise_id, user_id) references public.exercises (id, user_id) on delete cascade
);

create table if not exists public.daily_selections (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  muscle_group_id bigint not null,
  selected_date date not null,
  created_at timestamptz not null default now(),
  unique (user_id, muscle_group_id, selected_date),
  foreign key (muscle_group_id, user_id) references public.muscle_groups (id, user_id) on delete cascade
);

-- Libra chat history ----------------------------------------------------------

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  artifact jsonb,
  created_at timestamptz not null default now()
);

-- Indexes for the queries the app runs ----------------------------------------

create index if not exists trackers_user_idx on public.trackers (user_id);
create index if not exists logs_user_logged_idx on public.logs (user_id, logged_at);
create index if not exists logs_tracker_logged_idx on public.logs (tracker_id, logged_at);
create index if not exists notes_user_created_idx on public.notes (user_id, created_at desc);
create index if not exists muscle_groups_user_idx on public.muscle_groups (user_id, created_at);
create index if not exists exercises_group_idx on public.exercises (muscle_group_id);
create index if not exists exercises_user_idx on public.exercises (user_id);
create index if not exists exercise_logs_exercise_idx on public.exercise_logs (exercise_id, logged_at desc);
create index if not exists exercise_logs_user_logged_idx on public.exercise_logs (user_id, logged_at);
create index if not exists messages_user_created_idx on public.messages (user_id, created_at);

-- Row level security: own rows only, for every table --------------------------

do $$
declare
  t text;
begin
  foreach t in array array[
    'profiles', 'trackers', 'logs', 'notes', 'muscle_groups',
    'exercises', 'exercise_logs', 'daily_selections', 'messages'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);

    execute format('drop policy if exists "Select own rows" on public.%I', t);
    execute format('drop policy if exists "Insert own rows" on public.%I', t);
    execute format('drop policy if exists "Update own rows" on public.%I', t);
    execute format('drop policy if exists "Delete own rows" on public.%I', t);

    execute format('create policy "Select own rows" on public.%I for select to authenticated using ((select auth.uid()) = user_id)', t);
    execute format('create policy "Insert own rows" on public.%I for insert to authenticated with check ((select auth.uid()) = user_id)', t);
    execute format('create policy "Update own rows" on public.%I for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id)', t);
    execute format('create policy "Delete own rows" on public.%I for delete to authenticated using ((select auth.uid()) = user_id)', t);

    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end
$$;

-- An empty profile for every new user ------------------------------------------

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (user_id) values (new.id) on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
